const templateModules = import.meta.glob("@/assets/contract-templates/**/*.docx", {
  query: "?url",
  import: "default",
  eager: true,
}) as Record<string, string>;

function resolveTemplateUrl(filename: string): string {
  const key = Object.keys(templateModules).find((k) => k.endsWith(`/${filename}`));
  if (!key) throw new Error(`Template DOCX não encontrado: ${filename}`);
  return templateModules[key];
}

